/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  RCC->AHB1ENR |= RCC_AHB1ENR_GPIOCEN ;
  RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN ;
  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_I2C2_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_USART6_UART_Init();
  MX_USART3_UART_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_UART5_Init();
  MX_UART7_Init();
  /* USER CODE BEGIN 2 */

//  lcd_init ();
//  lcd_put_cur(0, 0);
//  lcd_send_string ("Motor Control Init");
//  lcd_put_cur(1, 0);
//  lcd_send_string("Agribot");
  RCC->APB2ENR |= RCC_APB2ENR_ADC1EN ;

  // i tried selecting Select ADC1_IN18 input channel. since the paragpghe said "
  /* 15.3.4 Channel selection
  There are 16 multiplexed channels. It is possible to organize the conversions in two groups:
  regular and injected. A group consists of a sequence of conversions that can be done on
  any channel and in any order. For instance, it is possible to implement the conversion
  sequence in the following order: ADC_IN3, ADC_IN8, ADC_IN2, ADC_IN2, ADC_IN0,
  ADC_IN2, ADC_IN2, ADC_IN15.
  • A regular group is composed of up to 16 conversions. The regular channels and their
  order in the conversion sequence must be selected in the ADC_SQRx registers. The
  total number of conversions in the regular group must be written in the L[3:0] bits in the
  ADC_SQR1 register.*/
  ADC1->SQR1 &= ~ADC_SQR1_L;             // L = 0  -> sequence length of 1 conversion
  ADC1->SQR3 = (18u << ADC_SQR3_SQ1_Pos);
  // 1st conversion = channel 18 (SQ1_Pos is 0, so this is just 18)
    //now i have to set the sampling time
  ADC1->SMPR1 |= ADC_SMPR1_SMP18;

  //3-Set the TSVREFE bit in the ADC_CCR register to wake up the temperature sensor
//  from power down mode
  ADC->CCR |= ADC_CCR_TSVREFE ;
  //4-Start the ADC conversion by setting the SWSTART bit
  ADC1->CR2 |=  ADC_CR2_SWSTART ;

  /* Start FlySky iBUS reception on USART6 (PC7) via DMA + IDLE line */
  ibus_init(&huart6);

  /* Configure TIM1 PWM + DIR/STOP GPIOs; both motors start stopped */
  motor_init();

  /* Start wheel-odometry pulse counters (TIM3=right/PD2, TIM4=left/PE0) */
  encoder_init();

  /* Start odometry TX bridge to the Pi over UART7 (PB4=TX, PB3=RX) */
  odom_init(&huart7);

  /* Start Pi cmd_vel RX on the same UART7 link (PB3) -- see cmd.h */
  cmd_init(&huart7);

ADC1->CR1 |= ADC_ALL_CHANNELS ;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    /* Poll arm button, sample wheel odometry, then drive. ~100 Hz. */
    motor_button_update();
    encoder_update();
    motor_rc_update();
    odom_update();          /* stream wheel odometry to the Pi @ 50 Hz */

    /* Throttled debug on the USART3 VCP (~5 Hz). */
    static uint32_t last_dbg = 0;
    if (HAL_GetTick() - last_dbg >= 200) {
      last_dbg = HAL_GetTick();
      const char *state = !motor_is_armed() ? "DISARMED"
                          : (ibus_is_alive(100) ? "ARMED" : "FAILSAFE");
      const char *src = (motor_drive_source() == DRIVE_RC)  ? "RC"
                       : (motor_drive_source() == DRIVE_CMD) ? "CMD"
                       : "-";
      /* velocity in mm/s as int -> avoids needing float-printf (-u _printf_float) */
      printf("%s src:%s  F:%lu E:%lu  cmdF:%lu cmdE:%lu  spd(CH2):%u steer(CH1):%u  vL:%d vR:%d mm/s  pL:%lu pR:%lu\r\n",
             state, src, ibus.frame_count, ibus.error_count,
             cmd_frame_count, cmd_error_count,
             ibus_get_channel(1), ibus_get_channel(0),
             (int)(encoder_speed_mps(MOTOR_LEFT)  * 1000.0f),
             (int)(encoder_speed_mps(MOTOR_RIGHT) * 1000.0f),
             encoder_pulses(MOTOR_LEFT), encoder_pulses(MOTOR_RIGHT));
    }
    HAL_Delay(10);
  }
  /* USER CODE END 3 */
}


