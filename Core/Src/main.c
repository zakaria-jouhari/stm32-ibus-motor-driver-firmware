{
    if (huart->Instance == USART6) {
        ibus_on_rx_event(Size);
    } else if (huart->Instance == UART7) {
        cmd_on_rx_event(Size);
    }
}

/* Recover the reception after an overrun/noise error, on either link */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART6) {
        ibus_on_error();
    } else if (huart->Instance == UART7) {
        cmd_on_error();
    }
}

